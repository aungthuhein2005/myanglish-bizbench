"""95% bootstrap confidence intervals for the benchmark scores (no API calls).

Usage:
    python scripts/bootstrap_ci.py [--version v0.2] [--n 2000]

Resamples the 100 test messages with replacement and recomputes intent Macro F1, exact match and
entity F1 from the saved predictions. Writes reports/<version>/confidence_intervals.md (reports/
for v0.1). A paired comparison shows how often model A beats model B on the same resample.
"""
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import evaluator  # noqa: E402
from src.evaluator import MODELS, load_predictions  # noqa: E402
from src.metrics import entity_scores, intent_scores  # noqa: E402

VERSION = sys.argv[sys.argv.index("--version") + 1] if "--version" in sys.argv else "v0.1"
N = int(sys.argv[sys.argv.index("--n") + 1]) if "--n" in sys.argv else 2000
evaluator.set_version(VERSION)
OUT_DIR = ROOT / "reports" if VERSION == "v0.1" else ROOT / "reports" / VERSION
OUT = OUT_DIR / "confidence_intervals.md"


def scores(gold, pred, idx):
    g = [gold[i] for i in idx]
    p = [pred[gold[i]["id"]] for i in idx]
    it = intent_scores([x["intents"] for x in g], [x["intents"] for x in p])
    en = entity_scores([x["entities"] for x in g], [x["entities"] for x in p])
    return it["macro_f1"], it["exact_match"], en["entity_f1"]


def ci(vals):
    v = sorted(vals)
    return v[int(0.025 * len(v))], v[int(0.975 * len(v)) - 1]


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    with open(ROOT / "data" / VERSION / "test.jsonl", encoding="utf-8") as fh:
        gold = [json.loads(line) for line in fh if line.strip()]
    preds = {m: load_predictions(m) for m in MODELS}
    preds = {m: p for m, p in preds.items() if all(g["id"] in p for g in gold)}
    models = list(preds)
    rng = random.Random(0)
    full = range(len(gold))
    samples = [[rng.randrange(len(gold)) for _ in full] for _ in range(N)]
    boot = {m: [scores(gold, preds[m], s) for s in samples] for m in models}
    point = {m: scores(gold, preds[m], full) for m in models}

    pct = lambda x: f"{100 * x:.1f}"  # noqa: E731
    out = [f"# Myanglish-BizBench {VERSION} — 95% bootstrap confidence intervals", "",
           f"{N} resamples of the {len(gold)} test messages (seed 0), from saved predictions. "
           "Generated by `scripts/bootstrap_ci.py`.", "",
           "| Model | Macro F1 [95% CI] | Exact match [95% CI] | Entity F1 [95% CI] |", "|---|---|---|---|"]
    for m in models:
        cells = []
        for k in range(3):
            lo, hi = ci([b[k] for b in boot[m]])
            cells.append(f"{pct(point[m][k])} [{pct(lo)}–{pct(hi)}]")
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    out += ["", "## Paired comparison", "",
            "Share of resamples in which the row model scores higher than the column model on "
            "**Macro F1** (same messages for both). Values above 97.5% or below 2.5% mean the "
            "difference is unlikely to be noise.", "",
            "| | " + " | ".join(models) + " |", "|---|" + "---|" * len(models)]
    for a in models:
        row = [f"**{a}**"]
        for b in models:
            row.append("—" if a == b else
                       f"{100 * sum(x[0] > y[0] for x, y in zip(boot[a], boot[b])) / N:.0f}%")
        out.append("| " + " | ".join(row) + " |")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
