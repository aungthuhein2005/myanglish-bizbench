"""Merge the reviewed v0.2 sheet into a dataset file and write a changelog.

Usage:
    python scripts/apply_review.py [path/to/review_sheet.csv]

Reads data/v0.2/review_sheet.csv (edited by the reviewer), checks that every row has
review_status "ok" or "changed", validates the result against the v0.2 rules, and writes:
    data/v0.2/reviewed.json     input for: python scripts/freeze_dataset.py --version v0.2
    reports/v0.2_changelog.md   every label that differs from v0.1, with the reviewer's notes

Editable columns: intents (space-separated), entities (JSON object), requires_clarification
(true/false), context (empty = none), difficulty, writing_style, english_meaning,
normalized_burmese. The text and id columns must not change.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from src.schemas import ISSUE_TYPES  # noqa: E402
from validate_dataset import format_summary, validate  # noqa: E402

BASE = ROOT / "data" / "v0.1" / "test.jsonl"
DEFAULT_SHEET = ROOT / "data" / "v0.2" / "review_sheet.csv"
OUT = ROOT / "data" / "v0.2" / "reviewed.json"
CHANGELOG = ROOT / "reports" / "v0.2_changelog.md"
EDITABLE = ["intents", "entities", "requires_clarification", "context", "difficulty",
            "writing_style", "english_meaning", "normalized_burmese"]


def parse_row(row, problems):
    rid = row["id"]
    status = row["review_status"].strip().lower()
    if status not in ("ok", "changed"):
        problems.append(f"{rid}: review_status must be 'ok' or 'changed' (got {row['review_status']!r})")
    try:
        entities = json.loads(row["entities"] or "{}")
    except json.JSONDecodeError as e:
        problems.append(f"{rid}: entities is not valid JSON ({e})")
        entities = {}
    clar = row["requires_clarification"].strip().lower()
    if clar not in ("true", "false"):
        problems.append(f"{rid}: requires_clarification must be true or false")
    return {
        "intents": row["intents"].split(),
        "entities": entities,
        "requires_clarification": clar == "true",
        "context": row["context"].strip() or None,
        "difficulty": row["difficulty"].strip(),
        "writing_style": row["writing_style"].strip(),
        "english_meaning": row["english_meaning"].strip(),
        "normalized_burmese": row["normalized_burmese"].strip(),
    }


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    sheet = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SHEET
    with open(BASE, encoding="utf-8") as fh:
        base = [json.loads(line) for line in fh if line.strip()]
    with open(sheet, encoding="utf-8-sig", newline="") as fh:
        rows = {r["id"]: r for r in csv.DictReader(fh)}

    problems = []
    if set(rows) != {r["id"] for r in base}:
        problems.append("the sheet must contain exactly the 100 v0.1 ids")
    records, changes = [], []
    for b in base:
        row = rows.get(b["id"])
        if row is None:
            continue
        if row["text"] != b["text"]:
            problems.append(f"{b['id']}: text was edited; message text must stay unchanged")
        new = parse_row(row, problems)
        rec = dict(b)
        rec.update(new)
        records.append(rec)
        diffs = [(f, b[f], rec[f]) for f in EDITABLE if b[f] != rec[f]]
        if diffs or row["reviewer_notes"].strip():
            changes.append((b, diffs, row["reviewer_notes"].strip(), row["review_status"].strip().lower()))
        if row["review_status"].strip().lower() == "ok" and diffs and not row["auto_changes"]:
            problems.append(f"{b['id']}: labels changed but review_status is 'ok' (use 'changed')")

    if problems:
        print("Review sheet has problems; nothing was written:")
        for p in problems:
            print("  -", p)
        sys.exit(1)

    summary = validate(records, set(ISSUE_TYPES))
    print(format_summary(summary))
    if summary["status"] != "PASS":
        for rid, errs in summary["errors"].items():
            for e in errs:
                print(f"  {rid}: {e}")
        sys.exit("Validation failed; nothing was written.")

    OUT.write_text(json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")
    n_label = sum(1 for _, d, _, _ in changes if any(f in ("intents", "entities") for f, _, _ in d))
    lines = ["# Myanglish-BizBench v0.2 — changes from v0.1", "",
             f"Generated by `scripts/apply_review.py` from `{sheet.name}`. "
             f"{len(changes)} of {len(records)} samples changed or annotated; {n_label} have different "
             "intent or entity labels. Rules: `reports/annotation_guidelines_v0.2.md`.", ""]
    for b, diffs, notes, _ in changes:
        lines.append(f"### {b['id']} — `{b['text']}`")
        for f, old, new in diffs:
            lines.append(f"- **{f}**: `{json.dumps(old, ensure_ascii=False)}` → "
                         f"`{json.dumps(new, ensure_ascii=False)}`")
        if notes:
            lines.append(f"- Reviewer note: {notes}")
        lines.append("")
    CHANGELOG.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {OUT}\nWrote {CHANGELOG} ({len(changes)} samples listed)")
    print("Next: python scripts/freeze_dataset.py --version v0.2")


if __name__ == "__main__":
    main()
