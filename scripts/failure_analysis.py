"""Failure analysis of saved benchmark predictions.

Usage (from the project root):
    python scripts/failure_analysis.py [--version v0.2]

Reads data/<version>/test.jsonl and that version's saved predictions (no API calls) and writes
a failure_analysis.md plus failure_cases.jsonl (every sample with all models' predictions, for
manual review): reports/ for v0.1, reports/<version>/ for later versions.
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import evaluator  # noqa: E402
from src.evaluator import MODELS, is_model_failure, load_predictions  # noqa: E402
from src.metrics import f1, gold_pairs, intent_scores, norm_value, pred_pairs  # noqa: E402
from src.schemas import ENTITY_KEYS, INTENTS  # noqa: E402

VERSION = sys.argv[sys.argv.index("--version") + 1] if "--version" in sys.argv else "v0.1"
evaluator.set_version(VERSION)
DATA = ROOT / "data" / VERSION / "test.jsonl"
OUT_DIR = ROOT / "reports" if VERSION == "v0.1" else ROOT / "reports" / VERSION
REPORT = OUT_DIR / "failure_analysis.md"
CASES = OUT_DIR / "failure_cases.jsonl"
REALTIME_P90_S = 3.0  # p90 latency budget used to call a model "real-time ready"


def pct(x):
    return "—" if x is None else f"{x * 100:.1f}"


def table(headers, rows):
    out = ["| " + " | ".join(map(str, headers)) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(map(str, r)) + " |" for r in rows]
    return "\n".join(out)


def prf(c):
    p = c["tp"] / (c["tp"] + c["fp"]) if c["tp"] + c["fp"] else None
    r = c["tp"] / (c["tp"] + c["fn"]) if c["tp"] + c["fn"] else None
    return p, r, f1(c["tp"], c["fp"], c["fn"])


def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def load():
    with open(DATA, encoding="utf-8") as fh:
        gold = [json.loads(line) for line in fh if line.strip()]
    preds = {}
    for name in MODELS:
        p = {i: r for i, r in load_predictions(name).items() if not r.get("error") or is_model_failure(r)}
        if len(p) == len(gold):
            preds[name] = p
    return gold, preds


def classify_entity_errors(g_pairs, p_pairs):
    """Split unmatched pairs into: near-miss value (same key, overlapping value), wrong key
    (same value, different key), missed (gold only) and extra (prediction only)."""
    fn, fp = set(g_pairs - p_pairs), set(p_pairs - g_pairs)
    cats = Counter()
    for g in list(fn):
        for p in list(fp):
            if g[0] == p[0] and (g[1] in p[1] or p[1] in g[1]):
                cats["near_miss_value"] += 1; fn.discard(g); fp.discard(p); break
    for g in list(fn):
        for p in list(fp):
            if g[1] == p[1] and g[0] != p[0]:
                cats["wrong_key"] += 1; fn.discard(g); fp.discard(p); break
    cats["missed"] += len(fn)
    cats["extra"] += len(fp)
    return cats


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    gold, preds = load()
    models = list(preds)
    n = len(gold)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = [f"# Myanglish-BizBench {VERSION} — failure analysis", "",
           f"Generated by `scripts/failure_analysis.py` from saved predictions of {len(models)} models on "
           f"{n} test samples (no new API calls). Every sample with all model outputs is in "
           "`reports/failure_cases.jsonl`.", ""]

    # 1. Per-intent F1 -------------------------------------------------------
    support = Counter(i for g in gold for i in g["intents"])
    per = {m: intent_scores([g["intents"] for g in gold], [preds[m][g["id"]]["intents"] for g in gold])
           for m in models}
    rows = []
    for lab in sorted(INTENTS, key=lambda l: statistics.mean(per[m]["per_intent_f1"].get(l, 0) for m in models)):
        vals = [per[m]["per_intent_f1"].get(lab) for m in models]
        rows.append([f"`{lab}`", support[lab]] + [pct(v) for v in vals]
                    + [pct(statistics.mean(v or 0 for v in vals))])
    out += ["## 1. Per-intent F1 — which business intents are hardest?", "",
            "Sorted from hardest (lowest mean F1 across models) to easiest. *n* = gold samples with the intent.", "",
            table(["intent", "n"] + models + ["mean"], rows), ""]

    # confusion: for each missed gold intent, what was predicted instead (all models pooled)
    missed_as = defaultdict(Counter)
    extra_when = defaultdict(Counter)
    for g in gold:
        gs = set(g["intents"])
        for m in models:
            ps = set(preds[m][g["id"]]["intents"])
            for lab in gs - ps:
                missed_as[lab].update(ps - gs or {"(nothing extra)"})
            for lab in ps - gs:
                extra_when[lab].update(gs)
    rows = []
    for lab in INTENTS:
        fn = sum(missed_as[lab].values()) and sum(
            1 for g in gold for m in models if lab in g["intents"] and lab not in preds[m][g["id"]]["intents"])
        fp = sum(1 for g in gold for m in models if lab not in g["intents"] and lab in preds[m][g["id"]]["intents"])
        top_inst = ", ".join(f"{k} ({v})" for k, v in missed_as[lab].most_common(3)) or "—"
        top_fp = ", ".join(f"{k} ({v})" for k, v in extra_when[lab].most_common(3)) or "—"
        rows.append([f"`{lab}`", fn or 0, top_inst, fp, top_fp])
    out += ["### Intent confusions (all models pooled)", "",
            "**Missed** counts model×sample cases where the gold intent was not predicted, and what was "
            "predicted instead. **Over-predicted** counts cases where the intent was predicted but not in gold, "
            "and which gold intents those samples had.", "",
            table(["intent", "missed", "predicted instead", "over-predicted", "gold intents of those samples"], rows), ""]

    # 2. Single vs multi-intent ----------------------------------------------
    groups = {"1 intent": [g for g in gold if len(g["intents"]) == 1],
              "2 intents": [g for g in gold if len(g["intents"]) == 2],
              "3+ intents": [g for g in gold if len(g["intents"]) >= 3]}
    rows = []
    for m in models:
        row = [m]
        for name, gs in groups.items():
            s = intent_scores([g["intents"] for g in gs], [preds[m][g["id"]]["intents"] for g in gs])
            row += [pct(s["micro_f1"]), pct(s["exact_match"])]
        rows.append(row)
    hdr = ["model"] + [f"{k} {x}" for k in groups for x in ("micro F1", "EM")]
    count_err = Counter()
    for gs_name, gs in groups.items():
        for g in gs:
            for m in models:
                p = set(preds[m][g["id"]]["intents"]); gset = set(g["intents"])
                if p != gset:
                    count_err[(gs_name, "too few" if len(p) < len(gset) else "too many" if len(p) > len(gset) else "same count, wrong label")] += 1
    err_rows = [[k] + [count_err[(k, t)] for t in ("too few", "same count, wrong label", "too many")] for k in groups]
    out += ["## 2. Single vs multi-intent — does complexity cause errors?", "",
            f"Samples: {', '.join(f'{k} = {len(v)}' for k, v in groups.items())}. EM = exact match of the intent set.", "",
            table(hdr, rows), "",
            "### Shape of exact-match errors (all models pooled)", "",
            "Whether a wrong intent set had fewer labels than gold (under-labelling), the same number, or more "
            "(over-labelling).", "",
            table(["gold", "too few", "same count, wrong label", "too many"], err_rows), ""]

    # 3. Entity precision / recall + error types -----------------------------
    rows, type_rows = [], []
    per_type = {m: defaultdict(Counter) for m in models}
    err_types = {m: Counter() for m in models}
    for m in models:
        c = Counter()
        for g in gold:
            gp, pp = gold_pairs(g["entities"]), pred_pairs(preds[m][g["id"]]["entities"])
            c["tp"] += len(gp & pp); c["fp"] += len(pp - gp); c["fn"] += len(gp - pp)
            for k, _ in gp & pp: per_type[m][k]["tp"] += 1
            for k, _ in pp - gp: per_type[m][k]["fp"] += 1
            for k, _ in gp - pp: per_type[m][k]["fn"] += 1
            err_types[m] += classify_entity_errors(gp, pp)
            c["pred_on_empty"] += bool(pp) and not gp
        p, r, f = prf(c)
        rows.append([m, c["tp"] + c["fn"], c["tp"] + c["fp"], c["tp"], pct(p), pct(r), pct(f), c["pred_on_empty"]])
        e = err_types[m]
        type_rows.append([m, e["near_miss_value"], e["wrong_key"], e["missed"], e["extra"]])
    out += ["## 3. Entity precision and recall — missing or hallucinating?", "",
            "Pairs are (key, normalised value). Precision below recall means the model adds entities the gold "
            "labels do not have; recall below precision means it misses labelled entities. "
            "**Extras on empty** = samples with no gold entities where the model still extracted something.", "",
            table(["model", "gold pairs", "predicted pairs", "correct", "precision", "recall", "F1", "extras on empty"], rows), "",
            "### Entity error types", "",
            "**Near-miss value**: right key, value overlaps but is not identical (e.g. `yankin` vs `yankin yangon`) — "
            "mostly an evaluation strictness issue. **Wrong key**: right value under another key. **Missed**: gold "
            "entity with no match. **Extra**: predicted entity with no match (a hallucination *or* an entity the "
            "gold labels left out).", "",
            table(["model", "near-miss value", "wrong key", "missed", "extra"], type_rows), ""]

    # 4. Per-entity-type F1 ---------------------------------------------------
    gold_type = Counter(k for g in gold for k, _ in gold_pairs(g["entities"]))
    rows = []
    for k in sorted(ENTITY_KEYS, key=lambda k: -gold_type[k]):
        cells = []
        for m in models:
            p, r, f = prf(per_type[m][k])
            cells.append("—" if not (per_type[m][k]["tp"] + per_type[m][k]["fn"] + per_type[m][k]["fp"])
                         else f"{pct(f)} ({pct(p)}/{pct(r)})")
        rows.append([f"`{k}`", gold_type[k]] + cells)
    out += ["## 4. Per-entity-type F1 — which information is hardest to extract?", "",
            "Cell = F1 (precision/recall). *n* = gold values of that type. Types with *n* = 0 only show "
            "precision problems (every prediction is an extra).", "",
            table(["entity", "n"] + models, rows), ""]

    # 5. Hardest samples -------------------------------------------------------
    cases = []
    for g in gold:
        wrong = [m for m in models if set(preds[m][g["id"]]["intents"]) != set(g["intents"])]
        cases.append({
            "id": g["id"], "text": g["text"], "english_meaning": g["english_meaning"],
            "source_model": g["source_model"], "difficulty": g["difficulty"],
            "gold_intents": g["intents"], "gold_entities": g["entities"],
            "models_wrong_intent": wrong,
            "predictions": {m: {"intents": preds[m][g["id"]]["intents"],
                                "entities": preds[m][g["id"]]["entities"]} for m in models},
        })
    CASES.write_text("\n".join(json.dumps(c, ensure_ascii=False) for c in cases) + "\n", encoding="utf-8")
    dist = Counter(len(c["models_wrong_intent"]) for c in cases)
    hard = sorted([c for c in cases if len(c["models_wrong_intent"]) >= len(models) // 2],
                  key=lambda c: (-len(c["models_wrong_intent"]), c["id"]))
    out += ["## 5. Failed predictions — linguistic or evaluation-related?", "",
            "How many models got each sample's intent set wrong:", "",
            table(["models wrong", "samples"], [[k, dist[k]] for k in range(len(models) + 1)]), "",
            f"### Samples that at least {len(models) // 2} of {len(models)} models got wrong", "",
            "Predicted intent sets are grouped; the number of models giving each answer is in brackets.", ""]
    for c in hard:
        answers = Counter(tuple(sorted(c["predictions"][m]["intents"])) for m in models)
        ans = "; ".join(f"{', '.join(a) or '(none)'} [{k}]" for a, k in answers.most_common())
        out += [f"**{c['id']}** ({c['source_model']}, {c['difficulty']}) — `{md_escape(c['text'])}`  ",
                f"Meaning: {md_escape(c['english_meaning'])}  ",
                f"Gold: {', '.join(c['gold_intents'])}  ",
                f"Models: {ans}", ""]

    # 6. Latency ---------------------------------------------------------------
    rows = []
    for m in models:
        lat = sorted(preds[m][g["id"]]["latency_s"] for g in gold)
        out_tok = [preds[m][g["id"]]["output_tokens"] for g in gold]
        p90 = lat[int(0.9 * (len(lat) - 1))]
        rows.append([m, f"{statistics.mean(lat):.1f}", f"{statistics.median(lat):.1f}", f"{p90:.1f}",
                     f"{lat[-1]:.1f}", f"{statistics.mean(out_tok):.0f}",
                     "yes" if p90 <= REALTIME_P90_S else "no"])
    rows.sort(key=lambda r: float(r[3]))
    out += ["## 6. Latency — which models suit real-time support?", "",
            "Wall-clock seconds per request as measured during the benchmark run (includes network time and "
            "any SDK retries; requests ran 1–8 in parallel, so treat these as indicative). **Real-time ready** "
            f"= p90 ≤ {REALTIME_P90_S:.0f} s.", "",
            table(["model", "mean", "median", "p90", "max", "mean output tokens", "real-time ready"], rows), ""]

    REPORT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {REPORT} and {CASES}")


if __name__ == "__main__":
    main()
